"""The Claude Code plugins in plugins/ and the marketplace in .claude-plugin/.

The tree is generated by scripts/build_claude_plugin.py from agents/skills/. These
tests keep it in sync with the sources, in the Agent Skills format, inside the plugin
directory's limits, content only, and free of instructions that read a person's
credentials or identity from the machine.

Deterministic: reads files only (and runs ``claude plugin validate`` only when the
claude CLI is on PATH); no clock, no network.
"""

import importlib.util
