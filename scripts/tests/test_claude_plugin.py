# --- manifests --------------------------------------------------------------------


def _versions():
    py = re.search(
        r'^version\s*=\s*"([^"]+)"', (ROOT / "pyproject.toml").read_text(encoding="utf-8"), re.M
    ).group(1)
    npm = json.loads((ROOT / "package.json").read_text(encoding="utf-8"))["version"]
    return py, npm


@pytest.mark.parametrize("plugin", PLUGIN_DIRS, ids=lambda p: p.name)
def test_plugin_manifest(plugin):
    manifest = json.loads((plugin / ".claude-plugin" / "plugin.json").read_text("utf-8"))
    py, npm = _versions()
    assert manifest["name"] == plugin.name
    assert manifest["version"] == py == npm
    assert manifest["license"] == "CC-BY-SA-4.0"
    assert manifest["author"]["name"] and manifest["description"]
    assert manifest["repository"] == "https://github.com/andreibesleaga/GABBE"


def test_marketplace_lists_every_plugin_folder():
    market = json.loads(MARKETPLACE.read_text(encoding="utf-8"))
    assert market["name"] == "gabbe"
    assert market["plugins"][0]["name"] == "gabbe"
    listed = {e["name"]: e for e in market["plugins"]}
    assert sorted(listed) == sorted(p.name for p in PLUGIN_DIRS)
    py, _ = _versions()
    for name, entry in listed.items():
        assert (ROOT / entry["source"]).resolve() == (PLUGINS / name).resolve()
        assert entry["source"].startswith("./plugins/")
        assert entry["version"] == py


@pytest.mark.parametrize("plugin", PLUGIN_DIRS, ids=lambda p: p.name)
def test_icon_is_a_square_png_of_512_to_2048_px_under_2_mb(plugin):
    png = (plugin / ".claude-plugin" / "icon.png").read_bytes()
    assert png[:8] == b"\x89PNG\r\n\x1a\n"
    assert png[12:16] == b"IHDR"
    w, h = int.from_bytes(png[16:20], "big"), int.from_bytes(png[20:24], "big")
    assert w == h and 512 <= w <= 2048, f"icon {w}x{h}"
    assert len(png) < 2 * 1024 * 1024


def test_icon_source_lives_outside_the_generated_tree(tmp_path, monkeypatch):
    """A build from an empty checkout (no plugins/) needs no --render-icon."""
    assert bcp.ICON.is_file() and bcp.PLUGINS not in bcp.ICON.parents
    monkeypatch.setattr(bcp, "PLUGINS", tmp_path / "absent")
    tree = bcp.build()
    assert tree["plugins/gabbe/.claude-plugin/icon.png"] == bcp.ICON.read_bytes()


# --- plugin directory limits and content only -------------------------------------


@pytest.mark.parametrize("plugin", PLUGIN_DIRS, ids=lambda p: p.name)
def test_plugin_is_within_the_directory_limits(plugin):
    files = [p for p in plugin.rglob("*") if p.is_file()]
    assert len(files) <= 512, f"{len(files)} files (limit 512)"
    for f in files:
        if f.suffix != ".png":
            assert f.stat().st_size < 256 * 1024, f"{_rel(f)} is 256 KiB or more"
        assert f.stat().st_size < 5 * 1024 * 1024
    readme = (plugin / "README.md").read_text(encoding="utf-8")
    prose = re.sub(r"```.*?```", "", readme, flags=re.S)
    assert len(prose.split()) >= 40, "README needs at least 40 words outside code"


def test_plugins_are_content_only():
    allowed = re.compile(
        r"^[a-z0-9-]+/(?:\.claude-plugin/plugin\.json|\.claude-plugin/icon\.png|README\.md"
        r"|skills/[a-z0-9-]+/(?:SKILL\.md|[A-Za-z0-9_./-]+\.(?:md|json|ya?ml|txt|csv|toml|xml)))$"
    )
    bad = [p.relative_to(PLUGINS).as_posix() for p in ALL_FILES]
    bad = [p for p in bad if not allowed.match(p)]
    assert not bad, f"unexpected files (no hooks, MCP, scripts or executables): {bad}"
    for p in ALL_FILES:
        if os.name != "nt":
            assert not os.access(p, os.X_OK), f"{_rel(p)} is executable"
        if p.suffix == ".md":
            text = p.read_text(encoding="utf-8")
            assert not re.search(r"!`[^`]+`", text), f"{_rel(p)} has a shell-injection line"
    for d in PLUGIN_DIRS:
        for name in ("hooks", "bin", "commands", "agents", ".mcp.json", ".lsp.json"):
            assert not (d / name).exists(), f"{d.name}/{name} must not exist"


def test_no_instruction_reads_credentials_or_identity_from_the_machine():
    """A hit is a finding for the owner in the named source skill or template: fix
    the source (or ask the person / use a userConfig option with sensitive: true)."""
    findings = []
    for p in ALL_FILES:
        if p.suffix == ".png":
            continue
        for n, line in enumerate(p.read_text(encoding="utf-8").splitlines(), 1):
            for rx, what in FORBIDDEN:
                if rx.search(line):
                    findings.append(f"{_rel(p)}:{n}: {what}: {line.strip()[:120]}")
    assert not findings, "Owner finding — credential/identity reads:\n" + "\n".join(findings)


def test_every_supporting_file_is_named_by_its_skill_or_a_copied_file():
    for skill in SKILL_FILES:
        folder = skill.parent
        extras = sorted(p for p in folder.rglob("*") if p.is_file() and p.name != "SKILL.md")
        if not extras:
            continue
        text = "\n".join(p.read_text(encoding="utf-8") for p in [skill] + extras)
        for p in extras:
            rel = p.relative_to(folder).as_posix()
            assert rel in text or p.name in text, f"{_rel(p)} is not referenced"


# Kit files a skill may name without them being copied: they wire an environment
# credential into a config, so the build leaves them out (see CREDENTIAL_RE).
NOT_COPIED = {"MCP_CONFIG_TEMPLATE.json"}


def _kit_template_or_guide(norm):
    """The kit file under agents/templates/ or agents/guides/ that a path names, if any."""
    agents = (ROOT / "agents").resolve()
    for cand in (ROOT / norm, ROOT / "agents" / norm):
        cand = cand.resolve()
        if cand.is_file() and agents in cand.parents:
            if cand.relative_to(agents).parts[0] in ("templates", "guides"):
                return cand
    return None


def test_every_kit_template_or_guide_a_skill_names_is_copied_beside_it():
    """A path in a SKILL.md (backticks or a Markdown link) that names an existing file
    under agents/templates/ or agents/guides/ resolves from the skill's own folder, so
    a plugin or skills.sh install, which has no agents/ tree, still has the file."""
    missing = []
    for skill in SKILL_FILES:
        _, body = _frontmatter(skill)
        for m in bcp.REF_RE.finditer(body):
            token = m.group(1) or m.group(2)
            norm = os.path.normpath(token).replace(os.sep, "/")
            if norm.startswith(("..", "/")) or Path(norm).name in NOT_COPIED:
                continue
            if _kit_template_or_guide(norm) and not (skill.parent / norm).is_file():
                missing.append(f"{_rel(skill)}: {token}")
    assert not missing, "Named kit files missing from the plugin:\n" + "\n".join(missing)


