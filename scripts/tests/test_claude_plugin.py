@pytest.mark.parametrize("skill", SKILL_FILES, ids=lambda p: p.parent.name)
def test_skill_frontmatter_meets_the_agent_skills_format(skill):
    meta, body = _frontmatter(skill)
    assert isinstance(meta, dict)
    assert set(meta) == {"name", "description", "license", "metadata"}
    name = meta["name"]
    assert name == skill.parent.name, "name equals the folder name"
    assert re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", name) and len(name) <= 64
    desc = meta["description"]
    assert isinstance(desc, str) and 0 < len(desc) <= 1024, f"description is {len(desc)} chars"
    assert meta["license"] == "CC-BY-SA-4.0"
    md = meta["metadata"]
    assert set(md) == {"source", "tags", "core", "context_cost"}
    assert all(isinstance(v, str) for v in md.values()), "metadata values are strings"
    assert md["core"] in ("true", "false")
    src = ROOT / md["source"]
    assert src.is_file(), f"metadata.source {md['source']} missing"
    src_meta, src_body = _frontmatter(src)
    assert body.startswith(src_body), "the body is the source body, unchanged"
    tail = body[len(src_body) :]
    assert tail == "" or tail.startswith("\n\n---\nPlugin note: the catalogue file(s)")
    assert desc.startswith(" ".join(str(src_meta["description"]).split()).rstrip("."))


