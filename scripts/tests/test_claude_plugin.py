ROOT = Path(__file__).resolve().parent.parent.parent
PLUGINS = ROOT / "plugins"
MARKETPLACE = ROOT / ".claude-plugin" / "marketplace.json"
SOURCES = sorted((ROOT / "agents" / "skills").rglob("*.skill.md"))

_spec = importlib.util.spec_from_file_location(
    "gabbe_build_claude_plugin", ROOT / "scripts" / "build_claude_plugin.py"
)
bcp = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(bcp)

PLUGIN_DIRS = sorted(p for p in PLUGINS.iterdir() if p.is_dir())
SKILL_FILES = sorted(PLUGINS.glob("*/skills/*/SKILL.md"))
ALL_FILES = sorted(p for p in PLUGINS.rglob("*") if p.is_file())

# Instructions that read a credential or a person's identity from the machine.
FORBIDDEN = [
    (re.compile(r"git\s+config\s+(?:--\S+\s+)*user\.(?:email|name)", re.I), "git identity"),
    (re.compile(r"\.npmrc|\.pypirc|\.netrc|\.git-credentials", re.I), "package/git credentials"),
    (re.compile(r"~/\.aws/credentials|~/\.ssh/|\bid_rsa\b|~/\.kube/config", re.I), "key files"),
    (re.compile(r"~/\.docker/config\.json|gh\s+auth\s+token", re.I), "token stores"),
    (re.compile(r"\b(?:cat|source|type|Get-Content)\s+\S*\.env\b", re.I), "reading .env"),
    (
        re.compile(r"\b(?:read|load|open|parse)\s+(?:the\s+)?(?:user's\s+)?`?\.env\b", re.I),
        "reading .env",
    ),
    (re.compile(r"security\s+find-(?:generic|internet)-password", re.I), "keychain"),
    (
        re.compile(r"\$\{?[A-Z][A-Z0-9_]*(?:TOKEN|KEY|SECRET|PASSWORD|CREDENTIALS?)\b"),
        "environment credential interpolation",
    ),
]


def _frontmatter(path):
    text = path.read_text(encoding="utf-8")
    assert text.startswith("---\n"), f"{path}: no frontmatter"
    end = text.find("\n---\n", 3)
    assert end != -1, f"{path}: unterminated frontmatter"
    return yaml.safe_load(text[4:end]), text[end + 5 :]


def _rel(p):
    return p.relative_to(ROOT).as_posix()


